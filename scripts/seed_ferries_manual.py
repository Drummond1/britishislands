TODAY = str(date.today())


def term(tid: str, name: str, lat: float, lon: float, country: str, *,
         island_id: str | None = None, operators: tuple[str, ...] = (),
         names_extra: dict | None = None) -> dict:
    names = {"en": name}
    if names_extra:
        names.update(names_extra)
    return {
        "id": tid,
        "name": name,
        "names": names,
        "lat": lat,
        "lon": lon,
        "country": country,
        "islandId": island_id,
        "islandDistanceKm": None,
        "osmNodeId": None,
        "wikidata": None,
        "operatorsServing": list(operators),
        "facilities": {"carPark": None, "evCharger": None, "stepFree": None, "ticketOffice": None, "cafe": None},
        "driveTimeMinutes": {"London": None, "Glasgow": None, "Edinburgh": None, "Belfast": None, "Dublin": None},
        "lastVerified": TODAY,
        "source": "manual",
    }


def route(rid: str, op: str, name: str, t_from: str, t_to: str, *,
          rtype: str = "car-and-foot",
          season: str = "year-round",
          freq: str = "daily",
          duration: int | None = None,
          booking: str | None = None,
          notes: str = "",
          island_from: str | None = None,
          island_to: str | None = None,
          sources: list[dict] | None = None,
          fare: float | None = None,
          accessibility: dict | None = None) -> dict:
    return {
        "id": rid,
        "operatorId": op,
        "operatorRouteCode": None,
        "name": name,
        "terminals": {
            "from": {"terminalId": t_from, "islandId": island_from},
            "to":   {"terminalId": t_to,   "islandId": island_to},
        },
        "type": rtype,
        "seasonality": season,
        "frequencyBand": freq,
        "durationMinutes": duration,
        "vessel": [],
        "vesselWikidata": [],
        "bookingUrl": booking,
        "timetable": {"source": "manual", "validFrom": None, "validTo": None, "weekly": [], "notes": notes},
        "accessibility": accessibility or {"wheelchair": None, "bicycle": None, "pets": None, "ev": None},
        "fareFromGBP": fare,
        "sources": sources or [],
        "lastVerified": TODAY,
    }


