"""Seed ``data/ferries_manual.json`` with the long tail of operators not
covered by OSM, GTFS, or per-operator scrapers (yet).

Each route here is hand-curated from each operator's published timetable
page. We deliberately omit detailed weekly schedules for operators where
ToS forbid republishing them; instead we record ``frequencyBand``,
``seasonality``, ``durationMinutes`` and ``timetable.notes`` plus a link
back to the operator's own page. The UI rolls that into a useful 'How to
get there' card without reproducing the operator's intellectual property.

Re-running this script overwrites ``data/ferries_manual.json`` with the
canonical seed contents below; downstream UI loads merge it into
``data/ferries.json`` at render time.
"""

from __future__ import annotations

